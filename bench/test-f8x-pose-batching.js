'use strict';
const assert = require('assert').strict;
const { ClusterRender } = require('../shared/cluster_render_client');
const wire = require('./renderer-wire');
const client = new ClusterRender('pose-frame-test', '/tmp/no-car'), writes = [];
let accept = true;
client.connected = client.ready = true;
client.sock = { write(bytes) { writes.push(Buffer.from(bytes)); return accept; } };
const a = client.image({ target: 'panel', w: 2, h: 2, iw: 2, ih: 2 });
const b = client.image({ target: 'panel', w: 2, h: 2, iw: 2, ih: 2 });
writes.length = 0;
client.batchPoses(() => {
    for (let i = 0; i < 1000; i++) client.set(a, { rotate: i });
    client.batchPoses(() => client.set(b, { rotate: 123 }));
    client.set(a, { opacity: 0.5 });
    assert.equal(writes.length, 0, 'no partial batch is delivered');
    assert.equal(client.poseBatch.size, 2, 'memory is bounded by layers, not sample count');
});
assert.equal(writes.length, 1);
const json = () => wire.frames(writes).map((frame) => JSON.parse(frame.slice(5)));
assert.deepEqual(json(), [{ op: 'set', ref: a, rotate: 999, opacity: 0.5 }, { op: 'set', ref: b, rotate: 123 }]);
assert.equal(client.poseBatch.size, 0);
writes.length = 0; accept = false;
client.batchPoses(() => { client.set(a, { rotate: 1 }); client.set(b, { rotate: 2 }); });
assert.equal(writes.length, 1, 'the entire current frame enters the socket together');
client.batchPoses(() => { for (let i = 0; i < 1000; i++) client.set(a, { rotate: i }); client.set(b, { rotate: 9 }); });
assert.equal(writes.length, 1, 'congestion does not append stale frame batches');
assert.equal(client.pendingSets.size, 2);
accept = true; client.blocked = false; client._pump();
assert.equal(client.pendingSets.size, 0);
assert.equal(json().filter((m) => m.ref === a).at(-1).rotate, 999);
writes.length = 0;
client.batchPoses(() => { client.set(a, { rotate: 50 }); client.drop(a); });
assert(!json().some((m) => m.op === 'set'), 'a drop inside a batch cannot revive its pose');
assert.equal(client.poseBatch.size, 0);
assert.throws(() => client.batchPoses(() => { client.set(b, { rotate: 10 }); throw new Error('test failure'); }), /test failure/);
assert.equal(client.poseBatchDepth, 0, 'an exception cannot strand a batch');
assert.equal(client.poseBatch.size, 0);
console.log('F8X pose batches: real consecutive stream framing, newest per-layer merge, nested frames, congestion, drop and exception cleanup passed.');
